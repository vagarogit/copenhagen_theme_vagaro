/* eslint-env node */
/**
 * Regenerates styles/vera/vera-force-light.css.
 *
 * The vendored Vagaro token files redefine ~163 design tokens inside
 * `@media (prefers-color-scheme: dark)`. vera-chat-widget has no light/dark
 * prop and ships no `dark:` variants of its own — it just consumes the tokens —
 * so a visitor whose OS is in dark mode gets a dark chat panel regardless of
 * the help center's own (light-only) design.
 *
 * This emits every dark-overridden token back at its LIGHT value, scoped to
 * #vera-chat-root. CSS variables inherit, so pinning them on the container
 * pins the whole widget subtree without touching the rest of the page.
 *
 * Run: node bin/generate-vera-force-light.mjs
 */
import fs from "fs";
import path from "path";

const SOURCES = ["styles/vera/vg-theme.css", "styles/vera/vg-theme-token.css"];
const OUT = "styles/vera/vera-force-light.css";
const DARK_AT = "@media (prefers-color-scheme: dark)";
const DARK_SELECTOR = 'html[data-theme="dark"]';

const declarations = new Map(); // token -> light value
const skipped = [];

for (const file of SOURCES) {
  const css = fs.readFileSync(path.resolve(file), "utf8");
  const darkIndex = css.indexOf(DARK_AT);
  if (darkIndex < 0) continue;

  // Each source is laid out as `:root, html[data-theme="light"]` →
  // `html[data-theme="dark"]` → the media query. Only the FIRST block holds
  // light values: slicing at the media query alone would sweep the explicit
  // dark-theme block in with them and emit dark values as "light" ones.
  const darkSelectorIndex = css.indexOf(DARK_SELECTOR);
  const lightEnd =
    darkSelectorIndex >= 0 ? Math.min(darkSelectorIndex, darkIndex) : darkIndex;

  const light = css.slice(0, lightEnd);
  const dark = css.slice(darkIndex);

  // Last light declaration wins, matching the cascade in the source file.
  const lightValues = new Map();
  for (const m of light.matchAll(/(--[A-Za-z0-9_-]+)\s*:\s*([^;]+);/g)) {
    lightValues.set(m[1], m[2].trim());
  }

  for (const m of dark.matchAll(/(--[A-Za-z0-9_-]+)\s*:/g)) {
    const token = m[1];
    if (declarations.has(token)) continue;
    if (!lightValues.has(token)) {
      // Only defined inside the dark block — there is no light value to
      // restore, so leave it alone rather than invent one.
      if (!skipped.includes(token)) skipped.push(token);
      continue;
    }
    declarations.set(token, lightValues.get(token));
  }
}

const body = [...declarations]
  .map(([token, value]) => `    ${token}: ${value};`)
  .join("\n");

const out = `/* GENERATED by bin/generate-vera-force-light.mjs — do not edit by hand.
   Re-run after re-vendoring vg-theme.css / vg-theme-token.css.

   Pins the Vera chat subtree to the light palette. The vendored token files
   flip these ${declarations.size} tokens under @media (prefers-color-scheme: dark);
   vera-chat-widget has no light/dark prop and no dark: variants of its own, so
   without this a dark-mode OS renders a dark panel inside a light help center.
   Scoped to #vera-chat-root — variables inherit, so the whole widget follows.${
     skipped.length
       ? `\n\n   Not restored (no light value exists in the source): ${skipped.join(", ")}.`
       : ""
   } */
@media (prefers-color-scheme: dark) {
  #vera-chat-root {
${body}
  }
}
`;

fs.writeFileSync(path.resolve(OUT), out);
console.log(
  `Wrote ${OUT}: ${declarations.size} tokens pinned to light` +
    (skipped.length ? `, ${skipped.length} skipped (${skipped.join(", ")})` : "")
);
